package NewJavaProgrames;

public class M1 {
	static void add()
	{
		int a=10;
		int b=20;
		int c=a+b;
		System.out.println(c);
	}
	static void sub()
	{
		int a=20;
		int b=10;
		int c=a-b;
		System.out.println(c);
	}
	static void div()
	{
		int a=10;
		int b=20;
		int c=b/a;
		System.out.println(c);
	}
	static void mul()
	{
		int a=10;
		int b=20;
		int c=a*b;
		System.out.println(c);
	}
	public static void main(String[] args) {
		System.out.println("this is first programe");
		add();
		sub();
		div();
		mul();
	}

}
